// Build the built-in HTML base design:
//   Style Dictionary → design/build/{tokens.css,manifest.json}
//   reset.css + tokens.css + components.css → design/build/base.css
//
// `base.css` is the bundle the Rust renderer embeds (synced to
// lib/rust/crates/pathland-render-html/assets/base.css).

import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import StyleDictionary from "style-dictionary";
import config from "../style-dictionary.config.mjs";
import { DESIGN_ROOT } from "./token-model.mjs";

const BUILD = join(DESIGN_ROOT, "build");

const BANNER = `/* Pathland HTML base design — generated by \`npm --prefix design run build\`. */
/* Edit design/tokens/** or design/html/{reset,components}.css, not this file. */
`;

async function readDesignFile(name) {
  return readFile(join(DESIGN_ROOT, name), "utf8");
}

export async function buildDesign() {
  await mkdir(BUILD, { recursive: true });
  const dictionary = new StyleDictionary(config);
  await dictionary.buildAllPlatforms();

  const [reset, tokens, components] = await Promise.all([
    readDesignFile("html/reset.css"),
    readFile(join(BUILD, "tokens.css"), "utf8"),
    readDesignFile("html/components.css"),
  ]);

  const base = [
    BANNER,
    reset.trim(),
    "",
    tokens.trim(),
    "",
    components.trim(),
    "",
  ].join("\n");

  const basePath = join(BUILD, "base.css");
  await writeFile(basePath, base, "utf8");
  // Content-hashed asset name for the SSR starters' cache-busting <link>.
  // The Rust renderer embeds this name (synced to assets/base.css.name).
  const hash = createHash("sha256").update(base, "utf8").digest("hex").slice(0, 12);
  await writeFile(join(BUILD, "base.css.name"), `base-${hash}.css\n`, "utf8");
  return basePath;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  buildDesign()
    .then((basePath) => {
      console.log(`design: wrote ${basePath}`);
      console.log("design: wrote build/tokens.css, build/manifest.json and build/base.css.name");
    })
    .catch((error) => {
      console.error(error);
      process.exitCode = 1;
    });
}
