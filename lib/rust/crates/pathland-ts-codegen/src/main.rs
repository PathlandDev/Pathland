/// Emit the token conventions (`lib/typescript/src/generated/tokens-core.ts`)
/// from `pathland_render_html::token_spec` — the pure data + pure functions the
/// DOM client imports, so the `--pl-*` naming / length rules cannot drift.
pub fn emit_tokens_core_ts() -> String {
    let mut out = String::new();
    out.push_str(
        "// Generated by `cargo run -p pathland-ts-codegen` (lib/rust). Do not edit.\n\
         // Canonical design-token conventions from `pathland-render-html::token_spec`\n\
         // (spec/TOKENS.md). Regenerate with `npm run regen`.\n\n",
    );
    let q = |s: &str| format!("{s:?}");
    let list = |items: &[&str]| {
        let joined: Vec<String> = items.iter().map(|s| q(*s)).collect();
        format!("[{}]", joined.join(", "))
    };
    let pair_list = |items: &[(&str, &str)]| {
        let joined: Vec<String> = items
            .iter()
            .map(|(a, b)| format!("[{}, {}]", q(*a), q(*b)))
            .collect();
        format!("[{}]", joined.join(", "))
    };
    writeln!(out, "export const DARK_PREFIX = {};", q(token_spec::DARK_PREFIX)).unwrap();
    writeln!(out, "export const VAR_PREFIX = {};", q(token_spec::VAR_PREFIX)).unwrap();
    writeln!(out, "export const SPACE_FAMILY = {};", q(token_spec::SPACE_FAMILY)).unwrap();
    writeln!(
        out,
        "export const LENGTH_PREFIXES: readonly string[] = {};",
        list(token_spec::LENGTH_PREFIXES)
    )
    .unwrap();
    writeln!(
        out,
        "export const LENGTH_PREFIX_SUFFIX: ReadonlyArray<readonly [string, string]> = {};",
        pair_list(token_spec::LENGTH_PREFIX_SUFFIX)
    )
    .unwrap();
    writeln!(
        out,
        "export const LENGTH_EXACT: readonly string[] = {};",
        list(token_spec::LENGTH_EXACT)
    )
    .unwrap();
    writeln!(
        out,
        "export const LENGTH_ELEVATION_SUFFIXES: readonly string[] = {};",
        list(token_spec::LENGTH_ELEVATION_SUFFIXES)
    )
    .unwrap();
    out.push_str(
        "\n/** The canonical CSS custom property for a token path: `--pl-` prefix, `.` → `-`.\n \
         *  The `dark.` scheme prefix is stripped — the dark variant overrides the same\n \
         *  variable inside a media query. */\n\
         export function tokenToCssVar(path: string): string {\n\
         \x20 const bare = path.startsWith(DARK_PREFIX) ? path.slice(DARK_PREFIX.length) : path;\n\
         \x20 return VAR_PREFIX + bare.replace(/[^A-Za-z0-9_-]/g, \"-\");\n\
         }\n\n\
         /** Whether a token path selects the dark variant. */\n\
         export function isDarkToken(path: string): boolean {\n\
         \x20 return path.startsWith(DARK_PREFIX);\n\
         }\n\n\
         /** Token paths whose F32 values are CSS lengths (emitted with `px`). */\n\
         export function isLengthToken(path: string): boolean {\n\
         \x20 for (const prefix of LENGTH_PREFIXES) {\n\
         \x20\x20 if (path.startsWith(prefix)) return true;\n\
         \x20 }\n\
         \x20 for (const [prefix, suffix] of LENGTH_PREFIX_SUFFIX) {\n\
         \x20\x20 if (path.startsWith(prefix) && path.endsWith(suffix)) return true;\n\
         \x20 }\n\
         \x20 if (LENGTH_EXACT.includes(path)) return true;\n\
         \x20 return path.startsWith(\"elevation.\") && LENGTH_ELEVATION_SUFFIXES.some((s) => path.endsWith(s));\n\
         }\n\n\
         /** Resolve a `DESIGN_TOKEN` property reference to a CSS expression: the\n\
          *  generative `space.<N>` family resolves to `calc(var(--pl-space-base) * N)`. */\n\
         export function resolveTokenCssRef(path: string): string {\n\
         \x20 const bare = path.startsWith(DARK_PREFIX) ? path.slice(DARK_PREFIX.length) : path;\n\
         \x20 if (bare.startsWith(SPACE_FAMILY)) {\n\
         \x20\x20 const rest = bare.slice(SPACE_FAMILY.length);\n\
         \x20\x20 if (rest.length > 0 && !Number.isNaN(Number(rest))) {\n\
         \x20\x20\x20 return `calc(var(--pl-space-base) * ${rest})`;\n\
         \x20\x20 }\n\
         \x20 }\n\
         \x20 return `var(${tokenToCssVar(bare)})`;\n\
         }\n",
    );
    out
}

/// Emit the role→semantic-element conventions (`generated/role-spec.ts`) from
/// `pathland_render_html::role_spec` — the single source the Rust SSR renderer
/// and the DOM client share for semantic tags / ARIA fallbacks.
pub fn emit_role_spec_ts() -> String {
    let mut out = String::new();
    out.push_str(
        "// Generated by `cargo run -p pathland-ts-codegen` (lib/rust). Do not edit.\n\
         // Canonical ROLE → semantic HTML element mapping from\n\
         // `pathland-render-html::role_spec` (spec/OPCODE.md §semantic properties).\n\
         // Regenerate with `npm run regen`.\n\n",
    );
    let q = |s: &str| format!("{s:?}");
    let nums = |items: &[u16]| {
        let joined: Vec<String> = items.iter().map(|v| format!("{v:#06x}")).collect();
        format!("[{}]", joined.join(", "))
    };
    let pair_list = |items: &[(u8, &str)]| {
        let joined: Vec<String> = items
            .iter()
            .map(|(r, s)| format!("[{r}, {}]", q(s)))
            .collect();
        format!("[{}]", joined.join(", "))
    };
    writeln!(
        out,
        "export const GENERIC_COMPONENTS: readonly number[] = {};",
        nums(role_spec::GENERIC_COMPONENTS)
    )
    .unwrap();
    writeln!(
        out,
        "export const NATIVE_ROLE_COMPONENTS: readonly number[] = {};",
        nums(role_spec::NATIVE_ROLE_COMPONENTS)
    )
    .unwrap();
    out.push_str(
        "export interface RoleTag {\n\
         \x20 role: number;\n\
         \x20 tag: string;\n\
         \x20 aria: string;\n\
         }\n\n",
    );
    out.push_str("export const ROLE_TAGS: readonly RoleTag[] = [\n");
    for rt in role_spec::ROLE_TAGS {
        writeln!(out, "  {{ role: {}, tag: {}, aria: {} }},", rt.role, q(rt.tag), q(rt.aria)).unwrap();
    }
    out.push_str("];\n\n");
    out.push_str("export const ROLE_ARIA: ReadonlyArray<readonly [number, string]> = ");
    out.push_str(&pair_list(role_spec::ROLE_ARIA));
    out.push_str(";\n\n");
    out.push_str(
        "/** A shell's role behavior (see `pathland-render-html::role_spec`).\n \
         *  Generic `div`/`span` shells may be retagged; native controls convey\n \
         *  their own role; anything else only gets an ARIA attribute. */\n\
         export type ShellKind = \"generic\" | \"native\" | \"other\";\n\n\
         /** The semantic tag a `(shell kind, role)` pair resolves to, or null. */\n\
         export function semanticTag(kind: ShellKind, role: number): string | null {\n\
         \x20 if (kind !== \"generic\") return null;\n\
         \x20 const found = ROLE_TAGS.find((r) => r.role === role);\n\
         \x20 return found ? found.tag : null;\n\
         }\n\n\
         /** The ARIA `role` value to emit for `(shell kind, role)`, or null when\n\
          *  the element already conveys the role (a semantic tag or a native control). */\n\
         export function ariaRole(kind: ShellKind, role: number): string | null {\n\
         \x20 if (kind === \"native\") return null;\n\
         \x20 const tagged = ROLE_TAGS.find((r) => r.role === role);\n\
         \x20 if (tagged) {\n\
         \x20\x20 return kind === \"generic\" ? null : tagged.aria;\n\
         \x20 }\n\
         \x20 const found = ROLE_ARIA.find(([r]) => r === role);\n\
         \x20 return found ? found[1] : null;\n\
         }\n",
    );
    out
}

fn main() -> io::Result<()> {
    let consts = constants_ts_path();
    std::fs::write(&consts, emit_constants_ts())?;
    println!("wrote {}", consts.display());
    let tokens = tokens_core_ts_path();
    if let Some(parent) = tokens.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(&tokens, emit_tokens_core_ts())?;
    println!("wrote {}", tokens.display());
    let roles = role_spec_ts_path();
    if let Some(parent) = roles.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(&roles, emit_role_spec_ts())?;
    println!("wrote {}", roles.display());
    Ok(())
}