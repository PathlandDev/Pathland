//! Generates `lib/typescript/src/constants.ts` from the canonical Rust protocol
//! constants (`pathland_core::constants`) so the TypeScript DOM renderer's
//! wire-constant mirror cannot drift: every `export const` below is bound to the
//! Rust constant it must match, so a rename breaks this crate's compilation and
//! a revalue changes the emitted file (caught by the CI regen-diff check).
//!
//! The enum *codes* (alignment, shape kind, role, state, …) are protocol-semantic
//! values defined in `spec/MODIFIERS.md`/`spec/OPCODE.md` that today live only in
//! the specs and the renderers; they are enumerated here so the TS side is
//! generated rather than hand-mirrored. They are the renderer-facing copy of the
//! same maps the HTML renderers implement.

use pathland_core::{
    category, component_type, environment, event, flag, listener, meta, property_id, role, style,
    tree, value_type,
};
use pathland_render_html::{role_spec, token_spec};
use std::fmt::Write;
use std::io;
use std::path::{Path, PathBuf};

/// The canonical source of the emitted file (resolved relative to this crate).
pub fn constants_ts_path() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../typescript/src/constants.ts")
}

/// The canonical source of the generated token conventions.
pub fn tokens_core_ts_path() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../typescript/src/generated/tokens-core.ts")
}

/// The canonical source of the generated role→element conventions.
pub fn role_spec_ts_path() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../typescript/src/generated/role-spec.ts")
}

fn fmt_u8(v: u8) -> String {
    format!("{v:#04x}")
}

fn fmt_u16(v: u16) -> String {
    format!("{v:#06x}")
}

fn fmt_u32(v: u32) -> String {
    format!("{v:#010x}")
}

fn write_consts(out: &mut String, prefix: &str, items: &[(&str, String)]) {
    for (name, value) in items {
        writeln!(out, "export const {prefix}{name} = {value};").unwrap();
    }
}

