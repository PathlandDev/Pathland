package dev.pathland.view.core

/** Canonical logical key codes carried by `KEY_DOWN`/`KEY_UP` (spec/EVENTS.md). */
object Keys {
    const val BACKSPACE = 0x08
    const val TAB = 0x09
    const val ENTER = 0x0D
    const val ESCAPE = 0x1B
    const val SPACE = 0x20
    const val PAGE_UP = 0x21
    const val PAGE_DOWN = 0x22
    const val END = 0x23
    const val HOME = 0x24
    const val ARROW_LEFT = 0x25
    const val ARROW_UP = 0x26
    const val ARROW_RIGHT = 0x27
    const val ARROW_DOWN = 0x28
    const val DELETE = 0x2E
}
